#!/usr/bin/env python3
"""Aggregate offline-simulator trial summaries into a Markdown table.

Reads every ``summary_<method>.json`` under ``results/offline_sim`` (written
by ``tools/simulate_navigation.py --output-dir``) and prints per-method,
per-scenario aggregates plus individual trials.  Writes the same text to
``results/offline_sim/summary.md``.
"""

from __future__ import annotations

import json
import math
import statistics
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
ROOT = PROJECT_ROOT / "results" / "offline_sim"


def fmt(values: list[float], digits: int = 2) -> str:
    values = [v for v in values if v is not None and math.isfinite(v)]
    if not values:
        return "-"
    if len(values) == 1:
        return f"{values[0]:.{digits}f}"
    return f"{statistics.mean(values):.{digits}f} ± {statistics.stdev(values):.{digits}f}"


def main() -> None:
    trials = []
    for path in sorted(ROOT.rglob("summary_*.json")):
        trials.extend(json.loads(path.read_text(encoding="utf-8")))
    if not trials:
        raise SystemExit(f"No summaries found under {ROOT}")
    order = ["nominal", "uncertain_start", "blocked_route", "kidnapped", "blocked_corridor"]
    groups: dict[tuple[str, str], list[dict]] = {}
    for trial in trials:
        groups.setdefault((trial["method"], trial["scenario"]), []).append(trial)

    lines = [
        "# Offline simulator results",
        "",
        "Generated by `tools/summarize_offline.py` from `tools/simulate_navigation.py` runs.",
        "Simulator results only; report Webots runs logged by the evaluation Supervisor.",
        "Success = mission complete reported, all 4 ordered goals reached by ground truth, no collision, final HOME error <= 0.20 m.",
        "Recovery time = time from the kidnap until the estimate stays within 0.20 m / 0.30 rad for 3 s.",
        "",
        "| Method | Scenario | Success | Goals | Time (s) | Path (m) | Collisions | Pos RMSE (m) | Head RMSE (rad) | Recovery (s) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for method in ("baseline", "team"):
        for scenario in order:
            group = groups.get((method, scenario))
            if not group:
                continue
            successes = sum(1 for t in group if t["success"])
            lines.append(
                f"| {method} | {scenario} | {successes}/{len(group)} "
                f"| {fmt([t['goals_reached'] for t in group], 1)} "
                f"| {fmt([t['completion_time_s'] for t in group if t['completion_time_s'] is not None], 0)} "
                f"| {fmt([t['path_length_m'] for t in group], 1)} "
                f"| {sum(t['collision_episodes'] for t in group)} "
                f"| {fmt([t['position_rmse_m'] for t in group], 3)} "
                f"| {fmt([t['heading_rmse_rad'] for t in group], 3)} "
                f"| {fmt([t['recovery_time_s'] for t in group if t.get('recovery_time_s') is not None], 1)} |"
            )
    lines += ["", "## Individual trials", "", "| Method | Scenario | Seed | Success | Goals | Time (s) | Path (m) | Collisions | Pos RMSE (m) | Recovery (s) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for method in ("baseline", "team"):
        for scenario in order:
            for t in sorted(groups.get((method, scenario), []), key=lambda t: t["seed"]):
                time_s = "-" if t["completion_time_s"] is None else f"{t['completion_time_s']:.0f}"
                recovery = "-" if t.get("recovery_time_s") is None else f"{t['recovery_time_s']:.1f}"
                lines.append(
                    f"| {method} | {scenario} | {t['seed']} | {'yes' if t['success'] else 'no'} | {t['goals_reached']} "
                    f"| {time_s} | {t['path_length_m']:.1f} | {t['collision_episodes']} | {t['position_rmse_m']:.3f} | {recovery} |"
                )
    text = "\n".join(lines) + "\n"
    (ROOT / "summary.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
