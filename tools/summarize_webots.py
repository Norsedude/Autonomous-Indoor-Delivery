#!/usr/bin/env python3
"""Aggregate Webots batch runs (``results/webots/runs.jsonl``) into Markdown.

Success follows ``tools/check_run_health.py --require-complete``: mission
complete, all ordered goals reached by ground truth, no collision, final HOME
error <= 0.20 m.  Heading RMSE is computed from each evaluation CSV when the
CSV is available locally.  Writes ``results/webots/summary.md``.
"""

from __future__ import annotations

import csv
import json
import math
import statistics
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
RUNS = PROJECT_ROOT / "results" / "webots" / "runs.jsonl"
OUTPUT = PROJECT_ROOT / "results" / "webots" / "summary.md"
SCENARIOS = ["nominal", "uncertain_start", "blocked_route", "kidnapped", "blocked_corridor"]
METHODS = ["baseline", "team", "team_robust"]
DEGRADATIONS = ["none", "moderate", "severe"]


def heading_rmse(record: dict) -> float | None:
    path = PROJECT_ROOT / record.get("csv", "")
    if not record.get("csv") or not path.is_file():
        return None
    values = []
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            try:
                values.append(float(row["heading_error_rad"]))
            except (KeyError, ValueError):
                continue
    return math.sqrt(sum(v * v for v in values) / len(values)) if values else None


def fmt(values, digits=2) -> str:
    values = [v for v in values if v is not None and math.isfinite(v)]
    if not values:
        return "-"
    if len(values) == 1:
        return f"{values[0]:.{digits}f}"
    return f"{statistics.mean(values):.{digits}f} ± {statistics.stdev(values):.{digits}f}"


def main() -> None:
    latest: dict[tuple, dict] = {}
    for line in RUNS.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        record.setdefault("degradation", "none")
        latest[(record["method"], record["scenario"], record["degradation"], record["seed"])] = record
    for record in latest.values():
        record["heading_rmse_rad"] = heading_rmse(record)
        # Mission success: the --require-complete criteria only.  The health
        # checker's "LiDAR telemetry >= 80 %" sanity rule is deliberately
        # violated by the injected scan dropouts of the extension, so it is
        # not part of success.
        record["health_pass"] = bool(
            record.get("mission_complete_reported")
            and (record.get("goals_reached_ground_truth") or 0) >= 4
            and (record.get("collision_episodes") or 0) == 0
            and record.get("final_home_error_m") is not None
            and record["final_home_error_m"] <= 0.20
        )

    groups: dict[tuple, list[dict]] = {}
    for (method, scenario, degradation, _), record in latest.items():
        groups.setdefault((method, scenario, degradation), []).append(record)

    lines = [
        "# Webots results",
        "",
        "Generated by `tools/summarize_webots.py` from `results/webots/runs.jsonl` (evaluation Supervisor logs).",
        "Success = the `--require-complete` mission criteria: mission complete, all 4 ordered goals by ground truth, no collision, final HOME error <= 0.20 m. (The health checker's LiDAR-availability sanity rule is excluded because the degraded-sensor runs drop scans on purpose; for undegraded runs the result equals the health check.)",
        "Values are mean ± standard deviation over seeds; time is reported for successful runs only.",
        "",
        "| Method | Scenario | Sensor degradation | Success | Goals | Time (s) | Path (m) | Collisions | Pos RMSE (m) | Head RMSE (rad) | Final HOME err (m) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for degradation in DEGRADATIONS:
        for scenario in SCENARIOS:
            for method in METHODS:
                group = groups.get((method, scenario, degradation))
                if not group:
                    continue
                passed = [r for r in group if r.get("health_pass")]
                lines.append(
                    f"| {method} | {scenario} | {degradation} | {len(passed)}/{len(group)} "
                    f"| {fmt([r.get('goals_reached_ground_truth') for r in group], 1)} "
                    f"| {fmt([r.get('duration_s') for r in passed], 0)} "
                    f"| {fmt([r.get('ground_truth_path_length_m') for r in group], 1)} "
                    f"| {sum(r.get('collision_episodes') or 0 for r in group)} "
                    f"| {fmt([r.get('position_rmse_m') for r in group], 3)} "
                    f"| {fmt([r.get('heading_rmse_rad') for r in group], 3)} "
                    f"| {fmt([r.get('final_home_error_m') for r in group], 2)} |"
                )
    lines += [
        "",
        "## Individual trials",
        "",
        "| Method | Scenario | Degradation | Seed | PASS | Goals | Time (s) | Collisions | Pos RMSE (m) | Issues |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key in sorted(latest, key=lambda k: (DEGRADATIONS.index(k[2]), SCENARIOS.index(k[1]), METHODS.index(k[0]), k[3])):
        r = latest[key]
        issues = "; ".join(r.get("issues") or []) or ""
        lines.append(
            f"| {key[0]} | {key[1]} | {key[2]} | {key[3]} | {'yes' if r.get('health_pass') else 'no'} "
            f"| {r.get('goals_reached_ground_truth')} | {(r.get('duration_s') or 0):.0f} | {r.get('collision_episodes')} "
            f"| {(r.get('position_rmse_m') or 0):.3f} | {issues} |"
        )
    text = "\n".join(lines) + "\n"
    OUTPUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
